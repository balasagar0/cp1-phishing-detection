"""Fills the document templates in docs/templates/ from reports/final_numbers.json (written by scripts/make_final_numbers.py on cp1-final).
  python scripts/render_docs.py            write every document
  python scripts/render_docs.py --check    exit 1 if a document is missing or out of date (tests/test_documents.py runs this)
docs/templates/<path> becomes docs/<path>. In a template, {{key}} is a value from final_numbers.json ("values"), and {{block:name}} is a
table built here from the same file. An unknown key stops the run. Templates hold no typed metric: tests/test_documents.py checks that."""
import argparse, json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]; TPL = ROOT / "docs" / "templates"; OUT = ROOT / "docs"
PH = re.compile(r"\{\{\s*([^{}]+?)\s*\}\}")


def blocks(doc):
    V = doc["values"]; g = V.__getitem__
    def demo():
        L = ["| Case | What it is | Channels | Event scores | Alerts alone? | Bundle risk | Outcome |", "|---|---|---|---|---|---|---|"]
        for r in doc["demo"]:
            p = f"demo.{r['id']}"; L.append(f"| {r['id']} | {g(p + '.name')} | {', '.join(r['channels'])} | {g(p + '.scores')} | {g(p + '.alone')} | {g(p + '.bundle')} | {g(p + '.alert')} |")
        return "\n".join(L)
    def corr():
        L = [f"| Method (SIMULATED bundles, alert line {g('alert_line')}) | Precision | Recall | F1 (95% CI) | False-positive rate (95% CI) |", "|---|---|---|---|---|"]
        for s, name in (("single", "Single-channel: alert if any event reaches the line"), ("parallel", "Parallel multi-channel: fusion without link and timing features"),
                        ("whole", "Correlation model on the whole bundle"), ("engine", f"Deployed engine, {g('window.minutes')}-minute windows (what the API does)")):
            L.append(f"| {name} | {g(f'corr.{s}.precision')} | {g(f'corr.{s}.recall')} | {g(f'corr.{s}.f1')} ({g(f'corr.{s}.f1_ci')}) | {g(f'corr.{s}.fpr')} ({g(f'corr.{s}.fpr_ci')}) |")
        return "\n".join(L)
    def detectors():
        L = ["| Detector | Measure | Precision | Recall | F1 | False-positive rate |", "|---|---|---|---|---|---|"]
        for c in [k.split(".")[2] for k in V if k.startswith("email.loco.") and k.endswith(".f1")]:
            p = f"email.loco.{c}"; L.append(f"| Email | Honest: {c} held out | {g(p + '.precision')} | {g(p + '.recall')} | {g(p + '.f1')} | {g(p + '.fpr')} |")
        L.append(f"| Email | **Honest: mean of the {g('email.n_corpora')} held-out runs** | see rows above | see rows above | **{g('email.honest.f1')}** | see rows above |")
        L.append(f"| Email | Flattering: pooled random split | {g('email.flattering.precision')} | {g('email.flattering.recall')} | {g('email.flattering.f1')} | {g('email.flattering.fpr')} |")
        L.append(f"| SMS | Honest: smishing vs rest | {g('sms.honest.precision')} | {g('sms.honest.recall')} | **{g('sms.honest.f1')}** (95% CI {g('sms.honest.f1_ci')}) | {g('sms.honest.fpr')} |")
        L.append(f"| SMS | Flattering: spam or smishing vs ham | {g('sms.flattering.precision')} | {g('sms.flattering.recall')} | {g('sms.flattering.f1')} | {g('sms.flattering.fpr')} |")
        L.append(f"| URL | Honest: hosts held out | {g('url.honest.precision')} | {g('url.honest.recall')} | **{g('url.honest.f1')}** (95% CI {g('url.honest.f1_ci')}) | {g('url.honest.fpr')} |")
        L.append(f"| URL | Flattering: feature benchmark, random split | {g('url.flattering.precision')} | {g('url.flattering.recall')} | {g('url.flattering.f1')} | {g('url.flattering.fpr')} |")
        return "\n".join(L)
    def exits():
        return "\n".join(["| # | Criterion | Result |", "|---|---|---|"] + [f"| {k.split('.')[-1]} | {name} | {g(k)} |" for k, name in EXIT_NAMES(V)])
    return {"demo": demo, "corr": corr, "detectors": detectors, "exit": exits}


def EXIT_NAMES(V):
    names = {"1": "All High-priority cases executed", "2": "Non-model cases: pass rate", "3": "All sample groups meet their targets",
             "4a": "Held-out metrics: the plan's held-out split", "4b": "The same line on the honest measures", "5": "Correlation changes a verdict with real models (SYS-14)",
             "6": "Speed tests (NFR-01, NFR-02)", "7": "No open Critical or High defects"}
    return [(f"tests.exit.{n}", names[n]) for n in names if f"tests.exit.{n}" in V]


def render(doc, text, rel):
    V, B = doc["values"], blocks(doc)
    def sub(m):
        k = m.group(1)
        if k.startswith("block:"):
            if k[6:] not in B: raise KeyError(f"{rel}: unknown block {k}")
            return B[k[6:]]()
        if k not in V: raise KeyError(f"{rel}: unknown key {k}")
        return V[k]
    out = PH.sub(sub, text)
    note = (f"> Generated by `scripts/render_docs.py` from `reports/final_numbers.json` (build `{doc['build']['tag']}`, commit `{doc['build']['commit7']}`). "
            f"Edit `docs/templates/{rel}`, not this file. Every number comes from the reports; none is typed.")
    lines = out.split("\n"); i = next((j for j, l in enumerate(lines) if l.startswith("# ")), -1)
    lines.insert(i + 1, "\n" + note); return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--check", action="store_true"); a = ap.parse_args()
    doc = json.loads((ROOT / "reports" / "final_numbers.json").read_text(encoding="utf-8")); stale = []
    for t in sorted(TPL.rglob("*.md")):
        rel = t.relative_to(TPL).as_posix(); dst = OUT / rel
        text = render(doc, t.read_text(encoding="utf-8"), rel)
        if a.check:
            if not dst.exists() or dst.read_text(encoding="utf-8") != text: stale.append(rel)
        else:
            dst.parent.mkdir(parents=True, exist_ok=True); dst.write_text(text, encoding="utf-8", newline="\n"); print("wrote", dst.relative_to(ROOT).as_posix())
    if a.check:
        print("out of date:", stale or "none"); sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
